-- Retired topic-based themes become reviewable intent-based themes.
UPDATE "feedback_items"
SET "status" = 'NEEDS_REVIEW'
WHERE "status" IN ('CLASSIFIED', 'CLASSIFYING', 'REVIEWED')
  AND "id" IN (
    SELECT "feedbackId"
    FROM "Classification"
    WHERE "theme" IN ('PRICING', 'ONBOARDING', 'PERFORMANCE')
  );

UPDATE "Classification"
SET "requiresHumanReview" = true
WHERE "theme" IN ('PRICING', 'ONBOARDING', 'PERFORMANCE');

-- Existing topic-specific alerts must not silently match broader intent labels.
UPDATE "AlertRule"
SET "isActive" = false
WHERE "theme" IN ('PRICING', 'ONBOARDING', 'PERFORMANCE')
  AND "isActive" = true;

ALTER TYPE "Theme" RENAME TO "Theme_old";

CREATE TYPE "Theme" AS ENUM (
  'BUG_PROBLEM',
  'FEATURE_REQUEST',
  'USABILITY_ISSUE',
  'QUESTION_SUPPORT',
  'PRAISE',
  'OTHER'
);

ALTER TABLE "Classification"
ALTER COLUMN "theme" TYPE "Theme"
USING (
  CASE "theme"::text
    WHEN 'BUG' THEN 'BUG_PROBLEM'
    WHEN 'FEATURE_REQUEST' THEN 'FEATURE_REQUEST'
    WHEN 'PRICING' THEN 'QUESTION_SUPPORT'
    WHEN 'ONBOARDING' THEN 'USABILITY_ISSUE'
    WHEN 'PERFORMANCE' THEN 'USABILITY_ISSUE'
    WHEN 'PRAISE' THEN 'PRAISE'
    ELSE 'OTHER'
  END
)::"Theme";

ALTER TABLE "ReviewAction"
ALTER COLUMN "previousTheme" TYPE "Theme"
USING (
  CASE "previousTheme"::text
    WHEN 'BUG' THEN 'BUG_PROBLEM'
    WHEN 'FEATURE_REQUEST' THEN 'FEATURE_REQUEST'
    WHEN 'PRICING' THEN 'QUESTION_SUPPORT'
    WHEN 'ONBOARDING' THEN 'USABILITY_ISSUE'
    WHEN 'PERFORMANCE' THEN 'USABILITY_ISSUE'
    WHEN 'PRAISE' THEN 'PRAISE'
    WHEN 'OTHER' THEN 'OTHER'
    ELSE NULL
  END
)::"Theme";

ALTER TABLE "ReviewAction"
ALTER COLUMN "newTheme" TYPE "Theme"
USING (
  CASE "newTheme"::text
    WHEN 'BUG' THEN 'BUG_PROBLEM'
    WHEN 'FEATURE_REQUEST' THEN 'FEATURE_REQUEST'
    WHEN 'PRICING' THEN 'QUESTION_SUPPORT'
    WHEN 'ONBOARDING' THEN 'USABILITY_ISSUE'
    WHEN 'PERFORMANCE' THEN 'USABILITY_ISSUE'
    WHEN 'PRAISE' THEN 'PRAISE'
    WHEN 'OTHER' THEN 'OTHER'
    ELSE NULL
  END
)::"Theme";

ALTER TABLE "AlertRule"
ALTER COLUMN "theme" TYPE "Theme"
USING (
  CASE "theme"::text
    WHEN 'BUG' THEN 'BUG_PROBLEM'
    WHEN 'FEATURE_REQUEST' THEN 'FEATURE_REQUEST'
    WHEN 'PRICING' THEN 'QUESTION_SUPPORT'
    WHEN 'ONBOARDING' THEN 'USABILITY_ISSUE'
    WHEN 'PERFORMANCE' THEN 'USABILITY_ISSUE'
    WHEN 'PRAISE' THEN 'PRAISE'
    WHEN 'OTHER' THEN 'OTHER'
    ELSE NULL
  END
)::"Theme";

DROP TYPE "Theme_old";
